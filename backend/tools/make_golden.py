"""Write the reference values the browser's copy of the indicators must match.

    cd backend && python tools/make_golden.py

Writes web/src/indicators/golden.json: made-up candles (5-minute and daily)
and every registered indicator's output on them with default settings. The web
tests compute the same indicators in TypeScript and fail on any difference;
backend/tests/test_golden.py fails if this file is out of date with the Python
library. Regenerate it whenever an indicator changes.
"""

from __future__ import annotations

import json
import math

import pandas as pd
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "tests"))
sys.path.insert(0, str(ROOT))

from conftest import daily_index, intraday_index, make_candles  # noqa: E402

from stockwizard.indicators import REGISTRY, compute  # noqa: E402
from stockwizard.scans import RULES, evaluate  # noqa: E402
from stockwizard.backtest import Strategy, report, run  # noqa: E402

OUT = ROOT.parent / "web" / "src" / "indicators" / "golden.json"


def _num(v):
    if v is None:
        return None
    if isinstance(v, bool):
        return v
    try:
        if v is getattr(__import__("pandas"), "NA"):
            return None
    except Exception:
        pass
    f = float(v)
    return None if math.isnan(f) else float(f"{f:.12g}")


def build() -> dict:
    frames = {
        "5m": make_candles(intraday_index(days=5), seed=21),
        "1d": make_candles(daily_index(days=300), seed=22),
    }
    out = {
        "note": "Generated by backend/tools/make_golden.py. Do not edit.",
        "registry": {
            name: {"version": i.version, "defaults": i.defaults, "intraday_only": i.intraday_only}
            for name, i in REGISTRY.items()
        },
        "frames": {},
    }
    for tf, df in frames.items():
        # Round first, so both sides compute on exactly the numbers in the file.
        df = df.map(lambda x: float(f"{x:.12g}"))
        frame = {
            "candles": {
                "time": [int(ts.timestamp()) for ts in df.index],
                **{c: [float(f"{x:.12g}") for x in df[c]] for c in ["open", "high", "low", "close", "volume"]},
            },
            "indicators": {},
        }
        for name, ind in REGISTRY.items():
            if ind.intraday_only and tf == "1d":
                continue
            params = {}
            if name == "anchored_vwap":
                params["anchor"] = df.index[len(df) // 4].isoformat()
            res = compute(name, df, tf, **params)
            frame["indicators"][name] = {
                "params": params,
                "columns": {c: [_num(v) for v in res[c].tolist()] for c in res.columns},
            }
        out["frames"][tf] = frame
    # Scan rules on the daily frame, default settings (plus a looser drawdown so it fires on made-up data).
    daily = frames["1d"].map(lambda x: float(f"{x:.12g}"))
    out["scans"] = {}
    for name in RULES:
        params = {"pct": 2.0} if name == "drawdown" else {}
        res = evaluate(name, daily, **params)
        out["scans"][name] = {
            "params": params,
            "hit": [None if v is pd.NA else bool(v) for v in res["hit"].tolist()],
            "direction": [None if v is pd.NA else v for v in res["direction"].tolist()],
            "values": {c: [_num(v) for v in res[c].tolist()] for c in res.columns if c not in ("hit", "direction")},
        }

    # Two whole backtests on made-up SPY and VIX: trades, skips and the full report.
    idx = daily_index(1500, first="2010-01-04")
    spy = make_candles(idx, seed=31).map(lambda x: float(f"{x:.12g}"))
    vix = make_candles(idx, seed=32, start=15.0).map(lambda x: float(f"{x:.12g}"))
    start, split = idx[50], idx[1000]
    out["backtest"] = {
        "candles": {sym: {"time": [int(t.timestamp()) for t in df.index], **{c: df[c].tolist() for c in ["open", "high", "low", "close", "volume"]}}
                    for sym, df in (("SPY", spy), ("VIX", vix))},
        "start": int(start.timestamp()),
        "split": int(split.timestamp()),
        "cases": [],
    }
    cases = [
        {"signal_symbol": "SPY", "signal_rule": "trend_break", "signal_params": {"length": 20}, "trade_symbol": "VIX",
         "target_pct": 10, "stop_pct": 5, "max_bars": 10, "cost_pct": 0.5},
        {"signal_symbol": "SPY", "signal_rule": "drawdown", "signal_params": {"lookback": 20, "pct": 2}, "trade_symbol": "VIX",
         "target_level": 16.5, "max_bars": 15},
        {"signal_symbol": "SPY", "signal_rule": "drawdown", "signal_params": {"lookback": 20, "pct": 2}, "trade_symbol": "VIX",
         "target_pct": 8, "stop_pct": 4, "max_bars": 10, "filter_symbol": "VIX", "filter_max": 14.5},
    ]
    for cfg in cases:
        res = run(Strategy("golden", **cfg), spy, vix, start, filter_candles=vix if cfg.get("filter_symbol") else None)
        rep = report(res, start, split)
        trades = []
        for t in res.trades:
            row = t.row()
            for k in ("signal_ts", "entry_ts", "exit_ts"):
                row[k] = int(pd.Timestamp(row[k]).timestamp()) if row[k] else None
            trades.append(row)
        out["backtest"]["cases"].append({"config": cfg, "trades": trades, "skipped": res.skipped, "report": rep})
    return out


def render() -> str:
    return json.dumps(build(), separators=(",", ":")) + "\n"


if __name__ == "__main__":
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(render())
    print(f"Wrote {OUT} ({OUT.stat().st_size // 1024} KB)")
