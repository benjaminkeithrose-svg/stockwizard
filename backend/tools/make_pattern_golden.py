"""Write the patterns the browser's copy must find (web/src/data/patterns-golden.json).

    cd backend && python tools/make_pattern_golden.py

Made-up daily candles, and for each of stockwizard.patterns' 18 patterns the candles where it's
complete. web/tests/patterns.test.ts runs web/src/data/patterns.ts on the same candles and fails
on any difference; backend/tests/test_patterns.py fails if this file is out of date.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "tests"))
sys.path.insert(0, str(ROOT))

from conftest import daily_index, make_candles  # noqa: E402

from stockwizard.patterns import PATTERNS, detect  # noqa: E402

OUT = ROOT.parent / "web" / "src" / "data" / "patterns-golden.json"
SETS = [("seed11", 11, 700), ("seed3", 3, 2500), ("flags", None, 0)]


def flag_candles():
    """Quiet stretches with a bull flag and a bear flag in them (random history rarely has a clean one)."""
    import pandas as pd
    rows = [(100.0, 100.5, 99.5, 100.0)] * 30
    rows += [(100 + 2 * i, 101.5 + 2 * i, 99.5 + 2 * i, 101.5 + 2 * i) for i in range(5)]    # pole up
    top = rows[-1][1]
    rows += [(top - 1.5, top - 0.5, top - 2.5, top - 1.5)] * 5 + [(top - 1.0, top + 1.5, top - 1.2, top + 1.2)]
    base = rows[-1][3]
    rows += [(base, base + 0.5, base - 0.5, base)] * 30
    rows += [(base - 2 * i, base - 2 * i + 0.5, base - 2 * i - 1.5, base - 2 * i - 1.5) for i in range(5)]   # pole down
    bottom = rows[-1][2]
    rows += [(bottom + 1.5, bottom + 2.5, bottom + 0.5, bottom + 1.5)] * 5 + [(bottom + 1.0, bottom + 1.2, bottom - 1.5, bottom - 1.2)]
    rows += [(bottom - 1.2, bottom - 0.7, bottom - 1.7, bottom - 1.2)] * 10
    idx = daily_index(len(rows))
    o, h, l, c = zip(*rows)
    return pd.DataFrame({"open": o, "high": h, "low": l, "close": c, "volume": 1000.0}, index=idx)


def render() -> str:
    out = {"note": "Generated by backend/tools/make_pattern_golden.py; do not edit.", "sets": []}
    for name, seed, n in SETS:
        c = (flag_candles() if seed is None else make_candles(daily_index(n), seed=seed)).round(10)   # the numbers the browser reads
        d = detect(c)
        out["sets"].append({
            "name": name,
            "candles": {k: [round(float(v), 10) for v in c[k]] for k in ("open", "high", "low", "close", "volume")},
            "time": [int(t.timestamp()) for t in c.index],
            "hits": {p: [int(i) for i in d.index.get_indexer(d.index[d[p]])] for p in PATTERNS},
        })
    return json.dumps(out, separators=(",", ":")) + "\n"


if __name__ == "__main__":
    OUT.write_text(render())
    print(f"Wrote {OUT}")
